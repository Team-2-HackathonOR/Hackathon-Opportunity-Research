-- Apply after the research schema. Approval and publication commit together.
CREATE TABLE IF NOT EXISTS public.event_suggestions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name text NOT NULL CHECK (char_length(event_name) BETWEEN 1 AND 160),
    website text NOT NULL CHECK (char_length(website) <= 2048 AND website ~* '^https?://'),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    submitted_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.event_suggestions
    ADD COLUMN IF NOT EXISTS reviewed_at timestamptz,
    ADD COLUMN IF NOT EXISTS reviewed_by uuid,
    ADD COLUMN IF NOT EXISTS review_notes text,
    ADD COLUMN IF NOT EXISTS published_event_id bigint UNIQUE
        REFERENCES hackathon_research.events(event_id);

ALTER TABLE public.event_suggestions ENABLE ROW LEVEL SECURITY;
GRANT USAGE ON SCHEMA public, hackathon_research TO service_role;
GRANT SELECT, INSERT, UPDATE ON public.event_suggestions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.event_suggestions_id_seq TO service_role;
GRANT INSERT ON hackathon_research.events, hackathon_research.event_tracks TO service_role;
GRANT USAGE, SELECT ON SEQUENCE
    hackathon_research.events_event_id_seq,
    hackathon_research.event_tracks_track_id_seq
TO service_role;

CREATE OR REPLACE FUNCTION public.moderate_event_suggestion(
    suggestion_id bigint,
    decision text,
    reviewer_id uuid,
    notes text,
    event_details jsonb DEFAULT '{}'::jsonb
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = pg_catalog
AS $$
DECLARE
    submission public.event_suggestions%ROWTYPE;
    published_id bigint;
BEGIN
    IF decision IS NULL OR decision NOT IN ('approved', 'rejected') OR reviewer_id IS NULL
       OR char_length(notes) > 2000
       OR (decision = 'rejected' AND coalesce(trim(notes), '') = '') THEN
        RAISE EXCEPTION 'Invalid moderation decision' USING ERRCODE = '22023';
    END IF;

    SELECT * INTO submission FROM public.event_suggestions
    WHERE id = suggestion_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Submission not found' USING ERRCODE = 'P0002';
    END IF;
    IF submission.status <> 'pending' THEN
        RAISE EXCEPTION 'Submission already reviewed' USING ERRCODE = 'P0001';
    END IF;

    IF decision = 'approved' THEN
        IF coalesce(trim(event_details->>'event_name'), '') = ''
           OR char_length(event_details->>'event_name') > 160
           OR coalesce(trim(event_details->>'organizer_name'), '') = ''
           OR coalesce(event_details->>'official_website', '') !~* '^https?://'
           OR coalesce(event_details->>'format', '') NOT IN ('in_person', 'virtual', 'hybrid')
           OR coalesce(event_details->>'event_start_date', '') = ''
           OR coalesce(trim(event_details->>'description'), '') = '' THEN
            RAISE EXCEPTION 'Complete event details are required' USING ERRCODE = '22023';
        END IF;

        INSERT INTO hackathon_research.events (
            event_name, organizer_name, official_website, registration_link,
            format, event_start_date, event_end_date, city, country,
            application_requirements, registration_fee_notes, operational_status,
            evidence_confidence, next_action
        ) VALUES (
            event_details->>'event_name', event_details->>'organizer_name',
            event_details->>'official_website', nullif(event_details->>'registration_link', ''),
            (event_details->>'format')::hackathon_research.event_format,
            (event_details->>'event_start_date')::date,
            nullif(event_details->>'event_end_date', '')::date,
            nullif(event_details->>'city', ''), nullif(event_details->>'country', ''),
            event_details->>'description', nullif(event_details->>'registration_fee_notes', ''),
            'needs_confirmation', 'low', 'Verify organizer rules and eligibility before applying.'
        ) RETURNING event_id INTO published_id;

        IF coalesce(trim(event_details->>'technical_tracks'), '') <> '' THEN
            INSERT INTO hackathon_research.event_tracks(event_id, track_type, track_name, description)
            VALUES (published_id, 'theme', event_details->>'technical_tracks', event_details->>'description');
        END IF;
    END IF;

    UPDATE public.event_suggestions
    SET status = decision, reviewed_at = now(), reviewed_by = reviewer_id,
        review_notes = notes, published_event_id = published_id
    WHERE id = suggestion_id;

    RETURN jsonb_build_object('id', suggestion_id::text, 'status', decision,
        'published_event_id', published_id::text);
END;
$$;

REVOKE ALL ON FUNCTION public.moderate_event_suggestion(bigint, text, uuid, text, jsonb)
FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.moderate_event_suggestion(bigint, text, uuid, text, jsonb)
TO service_role;

