create table if not exists public.event_suggestions (
  id bigint generated by default as identity primary key,
  event_name text not null check (char_length(event_name) between 1 and 160),
  website text not null check (
    char_length(website) <= 2048
    and website ~* '^https?://'
  ),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  submitted_at timestamptz not null default now()
);

alter table public.event_suggestions enable row level security;

grant usage on schema public to service_role;
grant insert on table public.event_suggestions to service_role;
grant usage, select on sequence public.event_suggestions_id_seq to service_role;
